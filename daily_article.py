# ─── Keyword Management ───────────────────────────────────────────────────────

def load_keywords() -> list:
    if not SEO_KEYWORDS_FILE.exists():
        print(f"ERROR: {SEO_KEYWORDS_FILE} が見つかりません", file=sys.stderr)
        sys.exit(1)
    return json.loads(SEO_KEYWORDS_FILE.read_text(encoding="utf-8"))


def save_keywords(data: list) -> None:
    SEO_KEYWORDS_FILE.write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def pick_next_keyword(keywords: list) -> dict | None:
    for entry in keywords:
        if not entry.get("used"):
            return entry
    return None


# ─── Main ─────────────────────────────────────────────────────────────────────

def main():
    dry_run = "--dry-run" in sys.argv

    # --list オプション
    if "--list" in sys.argv:
        keywords = load_keywords()
        used = [e for e in keywords if e.get("used")]
        unused = [e for e in keywords if not e.get("used")]
        print(f"キーワード総数: {len(keywords)}")
        print(f"使用済み: {len(used)}")
        print(f"未使用: {len(unused)}")
        print()
        print("【未使用キーワード】")
        for e in unused:
            print(f"  [{e['id']}] {e['keyword']}")
        return

    keywords = load_keywords()
    entry = pick_next_keyword(keywords)

    if entry is None:
        print("全てのキーワードを使用済みです。seo_keywords.json に新しいキーワードを追加してください。")
        sys.exit(0)

    kw = entry["keyword"]
    print(f"使用キーワード: {kw}")

    if kw not in ARTICLE_CONTENT:
        print(f"ERROR: キーワード '{kw}' に対応するコンテンツが ARTICLE_CONTENT にありません。")
        sys.exit(1)

    article = ARTICLE_CONTENT[kw]
    slug = article["slug"]
    filename = f"{slug}.html"
    out_path = PUBLIC_DIR / filename

    # ─── Generate HTML ──────────────────────────────────────────────────────
    PUBLIC_DIR.mkdir(exist_ok=True)
    html = build_html(article)
    out_path.write_text(html, encoding="utf-8")
    print(f"生成完了: {out_path.name}")

    if dry_run:
        print("[dry-run] git push をスキップします。")
        return

    # ─── Git push ───────────────────────────────────────────────────────────
    print("\n--- Git ---")
    subprocess.run(["git", "add", f"public/{filename}"], cwd=PROJECT_ROOT, check=True)
    status = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=PROJECT_ROOT, capture_output=True, text=True
    )
    if not status.stdout.strip():
        print("変更なし（ファイルが同一内容）。git commit をスキップします。")
    else:
        today = date.today().strftime("%Y-%m-%d")
        subprocess.run(
            ["git", "commit", "-m", f"[{today}] SEO article: {kw}"],
            cwd=PROJECT_ROOT, check=True,
        )
        subprocess.run(["git", "push"], cwd=PROJECT_ROOT, check=True)
        print("GitHub push 完了。")

    # ─── Mark keyword as used ───────────────────────────────────────────────
    for e in keywords:
        if e["keyword"] == kw:
            e["used"] = True
            e["used_date"] = date.today().isoformat()
            e["filename"] = filename
            break
    save_keywords(keywords)

    remaining = sum(1 for e in keywords if not e.get("used"))
    print(f"\nキーワード '{kw}' を使用済みにマークしました。")
    print(f"残りキーワード: {remaining} 件")


if __name__ == "__main__":
    main()
